/**
 * THE TITLE FORMULA, read off the channel's own numbers.
 *
 *   N [concrete visual thing] for [audience]  #Shorts
 *
 * 2026 content, all published within about two weeks of each other so age is
 * not confounding the comparison:
 *
 *   "N ___" listicle   15 videos   median 392   83.6 views/day   RETENTION 154.6%
 *   data / stat-led     7 videos   median 183   40.0 views/day   RETENTION  90.6%
 *
 * RETENTION IS THE FINDING, NOT THE VIEW COUNT. 154.6% average view percentage
 * means people are LOOPING — watching past the end and round again. That is the
 * signal Shorts distributes on, and it is why the gap compounds rather than
 * staying at 2x. The stat-led videos sit at 90.6%, meaning most viewers leave
 * before the end.
 *
 * SAMPLE SIZES ARE SMALL — 15 against 7. Treat this as a strong prior, not a
 * law, and re-derive it once there are fifty videos in each bucket.
 */
export const PACKAGING = `
THE FORMULA THAT WORKS
  N  +  concrete visual noun  +  for [audience]  +  #Shorts
  "6 Undercut Variations for Men"        1,799
  "6 Cuts to Ask Your Barber For"        1,260
  "6 Classic Mens Haircuts"              1,143
  "6 Hair Designs to Ask Your Barber For"  769

  - The number is always 6 in the winners. Do not vary it without a reason.
  - The noun must be SEEABLE. Undercut, fade, design, braid, loc, beard combo.
  - The audience qualifier does real work: "for Men", "for Women",
    "for Textured Hair". It tells the viewer this is for them in three words.
  - Keep it under about 45 characters before the hashtag.

THE ONE CTA THAT EARNED ITS PLACE
  "— Comment Your Number" took the second-best slot of the year at 1,260. It
  asks for a reply that costs one keystroke. Use it sparingly; it stops working
  when every title does it.

DO NOT OPEN A SHORT WITH A STATISTIC
  "Only 1.4% of Texas Barbershops Rate Below 4 Stars"      183
  "6,398 Texas Beauty Businesses, Ranked by Real Data"     173
  "569 Texas Barbershops Have a Perfect 5.0"               123
  "1,185 Barber & Cosmetology Schools, Ranked by Outcomes" 103

  Note the third one leads with a number and still fails — so it is not the
  number that works in the listicle formula, it is the PROMISE OF THINGS TO
  LOOK AT. A statistic is a conclusion; a listicle is a reason to keep watching.

  This does NOT mean the data is weak content. It is the strongest asset the
  business has. It belongs where someone is already looking for it — search —
  and kit lists prove that works. Wrong container, not wrong material.
`;

